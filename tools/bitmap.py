#!/usr/bin/env python3
"""Export / re-import OLED bitmaps of the firmware image table as ASCII art.

    bitmap.py list   image.bin                      list all images (id, address, size)
    bitmap.py export image.bin <id> out.txt         dump image as '#'/'.' ASCII art
    bitmap.py patch  image.bin <id> art.txt [-o x.patch]
                                                    emit a .patch for every changed byte

Image table (fw 1563): 640 x u32 at 0x0802DF94, bitmap data base 0x0800E600
    entry = offset:19 | pages:5 << 19 | width:8 << 24
Bitmaps are SSD1306 page format: per 8-pixel page row, one byte per column, LSB = top pixel.
The display is 128x64 (8 pages).
"""
import argparse
import struct
import sys
from pathlib import Path

BASE = 0x08008000
TABLE = 0x0802DF94
COUNT_PTR = 0x08036A6C   # u32 image count
DATA = 0x0800E600


def u32(img, addr):
    return struct.unpack_from("<I", img, addr - BASE)[0]


def entries(img):
    count = u32(img, COUNT_PTR)
    for i in range(count):
        e = u32(img, TABLE + 4 * i)
        yield i, DATA + (e & 0x7FFFF), (e >> 19) & 0x1F, e >> 24


def lookup(img, image_id):
    for i, addr, pages, width in entries(img):
        if i == image_id:
            return addr, pages, width
    sys.exit(f"image {image_id} not in table")


def to_art(data, width, pages):
    rows = []
    for p in range(pages):
        for bit in range(8):
            rows.append("".join("#" if data[p * width + x] >> bit & 1 else "." for x in range(width)))
    return "\n".join(rows) + "\n"


def from_art(text, width, pages):
    rows = [r for r in text.splitlines() if r and not r.startswith(";")]
    if len(rows) != pages * 8 or any(len(r) != width for r in rows):
        sys.exit(f"art must be {width}x{pages * 8} ('#' = on, '.' = off, ';' comment lines)")
    out = bytearray(width * pages)
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch == "#":
                out[(y // 8) * width + x] |= 1 << (y % 8)
    return bytes(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("list").add_argument("bin")
    p = sub.add_parser("export"); p.add_argument("bin"); p.add_argument("id", type=lambda s: int(s, 0)); p.add_argument("out")
    p = sub.add_parser("patch"); p.add_argument("bin"); p.add_argument("id", type=lambda s: int(s, 0)); p.add_argument("art")
    p.add_argument("-o", "--out")
    p.add_argument("--title", help="first comment line (shown by send_syx.py)")
    a = ap.parse_args()
    img = Path(a.bin).read_bytes()

    if a.cmd == "list":
        for i, addr, pages, width in entries(img):
            if width > 1:
                print(f"{i:4d} (0x{i:03x})  0x{addr:08x}  {width}x{pages * 8}")
        return

    addr, pages, width = lookup(img, a.id)
    orig = img[addr - BASE: addr - BASE + width * pages]
    if a.cmd == "export":
        Path(a.out).write_text(to_art(orig, width, pages))
        print(f"image {a.id}: {width}x{pages * 8} @ 0x{addr:08x} -> {a.out}")
        return

    new = from_art(Path(a.art).read_text(), width, pages)
    lines = [f"# {a.title}"] if a.title else []
    lines += [f"# generated by tools/bitmap.py from {a.art} (image {a.id}, {width}x{pages * 8} @ 0x{addr:08x})"]
    i = 0
    while i < len(new):  # group consecutive changed bytes into one line
        if new[i] == orig[i]:
            i += 1
            continue
        j = i
        while j < len(new) and new[j] != orig[j]:
            j += 1
        lines.append(f"0x{addr + i:08x}  {orig[i:j].hex()}  {new[i:j].hex()}")
        i = j
    text = "\n".join(lines) + "\n"
    if a.out:
        Path(a.out).write_text(text)
        print(f"{len(lines) - 1} patch lines -> {a.out}")
    else:
        sys.stdout.write(text)


if __name__ == "__main__":
    main()
